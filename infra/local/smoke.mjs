// Drives one import through the local stack as the administrator would:
// create project -> import inbox file -> wait for script review -> approve
// the latest script -> wait for the preview. Stops before any publishing.
const baseUrl = process.env.BASE_URL;
const adminOrigin = process.env.ADMIN_ORIGIN;
const inboxFileId = process.env.INBOX_FILE_ID;
const timeoutMs = 30 * 60 * 1000;
const stopStates = new Set(["FAILED", "CANCELLED", "EXPIRED", "RIGHTS_BLOCKED", "MANUAL_REVIEW_REQUIRED", "TIMING_REVIEW_REQUIRED"]);
const runId = Date.now().toString(36);
const startedAt = Date.now();

function elapsed() {
  return `${((Date.now() - startedAt) / 1000).toFixed(1).padStart(6)}s`;
}

async function api(path, { body, method = "GET", mutation } = {}) {
  const headers = { "content-type": "application/json" };
  if (mutation) {
    const csrf = await api("/api/v1/session/csrf-token");
    Object.assign(headers, { "idempotency-key": `${mutation}-${runId}`, origin: adminOrigin, "x-csrf-token": csrf.token });
  }
  const response = await fetch(`${baseUrl}${path}`, { body: body && JSON.stringify(body), headers, method });
  const text = await response.text();
  if (!response.ok) throw new Error(`${method} ${path} -> HTTP ${response.status}: ${text}`);
  return text ? JSON.parse(text) : undefined;
}

async function waitForState(jobId, wanted, seen) {
  const deadline = startedAt + timeoutMs;
  while (Date.now() < deadline) {
    const { items } = await api(`/api/v1/jobs/${jobId}/events?limit=100`);
    for (const event of items.slice(seen.count)) {
      console.log(`${elapsed()}  ${event.eventType.padEnd(24)} ${event.previousState ?? "-"} -> ${event.nextState ?? "-"}`);
    }
    seen.count = items.length;
    const state = items.at(-1)?.nextState;
    if (state === wanted) return;
    if (stopStates.has(state)) throw new Error(`Job stopped at ${state}; see the agent log: docker compose logs agent`);
    await new Promise((resolve) => setTimeout(resolve, 3000));
  }
  throw new Error(`Timed out waiting for ${wanted}`);
}

const health = await api("/api/v1/health");
console.log(`control plane ${health.deploymentVersion} is up`);

const project = await api("/api/v1/projects", { body: { name: `Local smoke ${runId}` }, method: "POST", mutation: "project" });
const { jobId } = await api(`/api/v1/projects/${project.id}/imports`, {
  body: {
    allowedProcessors: ["GOOGLE_GEMINI"],
    locator: { inboxFileId, kind: "OCI_INBOX_FILE" },
    rightsEvidence: "Local synthetic fixture generated by infra/local/make-fixture.sh; no third-party rights involved.",
  },
  method: "POST",
  mutation: "import",
});
console.log(`job ${jobId} queued for ${inboxFileId}`);

const seen = { count: 0 };
await waitForState(jobId, "WAITING_SCRIPT_REVIEW", seen);

const scripts = await api(`/api/v1/jobs/${jobId}/scripts?limit=100`);
const latest = scripts.items.at(-1);
console.log(`${elapsed()}  approving script version ${latest.version} (${latest.contentHash.slice(0, 12)}...)`);
await api(`/api/v1/jobs/${jobId}/scripts/approve`, {
  body: { contentHash: latest.contentHash, jobId, scriptVersion: latest.version },
  method: "POST",
  mutation: "approve-script",
});

await waitForState(jobId, "WAITING_PUBLISH_APPROVAL", seen);
const renders = await api(`/api/v1/jobs/${jobId}/renders?limit=100`);
console.log(`${elapsed()}  preview ready: ${JSON.stringify(renders.items.at(-1) ?? renders)}`);
console.log("SMOKE PASSED: import -> transcription -> translation -> approval -> voice -> render -> preview");
